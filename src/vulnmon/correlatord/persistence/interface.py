"""Domain operations; intentionally not a generic SQL abstraction.

Each operation is one or more bounded units of work; implementations must not
hold the writer lock or a live connection between calls.
"""
from typing import Protocol

BatchToken = tuple


class StaleBatch(RuntimeError):
    """Inputs or job progress changed since the batch was read; it was discarded."""


class Persistence(Protocol):
    def migrate(self) -> dict: ...
    def ingest_inventory(self, snapshot: dict) -> dict: ...
    def ingest_advisory(self, advisory: dict) -> dict: ...
    def next_batch(self, limit: int) -> tuple[BatchToken, list[dict]] | None: ...
    def commit_batch(self, token: BatchToken, results: list[dict]) -> None: ...
    def status(self) -> dict: ...
    def findings(self, after: int, limit: int) -> list[dict]: ...
    def events(self, after: int, limit: int) -> list[dict]: ...
